# Converts c/src/game/game_num.c (the numbers of the game: options and
# tables) into Atmos, and writes the two dumps that check it.
# usage: python3 tools/game_num.py c/src/game/game_num.c src/game/game_num.atm tst/c/game_num.c tst/game_num.atm
import re, sys
src = open(sys.argv[1]).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
macros = dict(re.findall(r'#define (\w+) (\{[^\n]*\})', src))
src = re.sub(r'#define[^\n]*\n', '', src)
for k, v in macros.items():
    src = re.sub(r'\b%s\b' % k, v, src)
decls = re.findall(r'^(bool|int|uint8_t|uint16_t) (\w+)((?:\[[^\]]*\])*) = (.*?);', src, flags=re.S | re.M)

def value(v):
    v = ' '.join(v.split())
    return v.replace('{', '[').replace('}', ']')

atm = [';; Port of c/src/game/game_num.c and game_num.h: the numbers of the game,',
       ';; which a PBX file may change. Generated by tools/game_num.py.', '',
       'include "game_types.atm"', '',
       'val GAME_NG_TECH_NEVER = 1 << 0', 'val GAME_NG_TECH_ALWAYS = 1 << 1',
       'val BASE_HP_TBL_NUM = 7', 'val TRAIT1_TBL_NUM = 10', 'val TRAIT2_TBL_NUM = 12', 'val PSHIELD_NUM = 5', '']
cd = ['/* The oracle of tst/game_num.atm: every number of c/src/game/game_num.c.',
      '   Generated with it. Not part of the port. */',
      '#include <stdio.h>', '#include "game_num.h"', '', 'int main(void)', '{']
ad = [';; game_num.atm of the port: every number, as tst/c/game_num.c prints it.',
      ';; Generated with it.', '', 'include "../src/game/game_num.atm"', '', 'pin out = []', '']
for ctype, name, dims, init in decls:
    dl = re.findall(r'\[([^\]]*)\]', dims)
    if dl:
        atm.append('pin %s = %s    ;; %s%s' % (name, value(init), ctype, dims))
        idx = ''.join('[i%d]' % k for k in range(len(dl)))
        cl = '    '
        for k, n in enumerate(dl):
            cl += 'for (int i%d = 0; i%d < (int)(sizeof(%s%s) / sizeof(%s%s[0])); ++i%d) ' % (k, k, name, ''.join('[0]' for _ in range(k)), name, ''.join('[0]' for _ in range(k)), k)
        cl += '{ printf("%s%s = %%i\\n"%s, %s%s); }' % (name, '[%i]' * len(dl), ''.join(', i%d' % k for k in range(len(dl))), name, idx)
        cd.append(cl)
        al = ''
        acc = name
        for k in range(len(dl)):
            al += 'loop i%d in #%s { ' % (k, acc)
            acc += '@(i%d)' % k
        al += 'set out@+ = string.format("%s%s = %%i\\n"%s, %s)' % (name, '[%i]' * len(dl), ''.join(', i%d' % k for k in range(len(dl))), acc)
        al += ' }' * len(dl)
        ad.append(al)
    else:
        if ctype == 'bool':
            atm.append('var %s = %s' % (name, init.strip()))
            ad.append('set out@+ = string.format("%s = %%i\\n", if %s => 1 => 0)' % (name, name))
        else:
            atm.append('var %s = %s    ;; %s' % (name, init.strip(), ctype))
            ad.append('set out@+ = string.format("%s = %%i\\n", %s)' % (name, name))
        cd.append('    printf("%s = %%i\\n", %s);' % (name, name))
cd += ['    return 0;', '}']
ad += ['io.write(string.join(out, ""))']
open(sys.argv[2], 'w').write('\n'.join(atm) + '\n')
open(sys.argv[3], 'w').write('\n'.join(cd) + '\n')
open(sys.argv[4], 'w').write('\n'.join(ad) + '\n')
print(len(decls), 'declarations')
