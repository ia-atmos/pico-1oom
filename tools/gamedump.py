# Writes the dump of the whole state of the game (every field of struct
# game_s, also those that are not saved), in C (tst/c/gamedump.h) and in
# Atmos (tst/gamedump.atm), from the structures of the C headers. The two
# print the same lines for the same state: the oracle of the steps that
# change fields that the save does not keep.
# usage: python3 tools/gamedump.py c/src/game tst/c/gamedump.h tst/gamedump.atm
import re, sys
d = sys.argv[1]
src = ''
for h in ('game.h', 'game_planet.h', 'game_shipdesign.h'):
    src += open(d + '/' + h).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
src = re.sub(r'//[^\n]*', '', src)
consts = {'PLAYER_NUM': 6, 'NUM_SHIPDESIGNS': 6, 'TECH_FIELD_NUM': 6, 'TECH_TIER_NUM': 10,
          'TECH_PER_FIELD': 60, 'PLANETS_MAX': 108, 'FLEET_ENROUTE_MAX': 260, 'TRANSPORT_MAX': 100,
          'NEWTECH_MAX': 15, 'TECH_NEXT_MAX': 12, 'GAME_EVENT_TBL_NUM': 20, 'HELP_SHOWN_NUM': 16,
          'EMPEROR_NAME_LEN': 15, 'NEBULA_MAX': 4, 'PLANET_NAME_LEN': 12, 'PLANET_SLIDER_NUM': 5,
          'FINISHED_NUM': 6, 'SHIP_NAME_LEN': 12, 'WEAPON_SLOT_NUM': 4, 'SPECIAL_SLOT_NUM': 3,
          'TECH_SPY_MAX': 6}
def num(x):
    x = x.strip()
    return consts[x] if x in consts else eval(x, {}, dict(consts))
structs = {}
for name, body in re.findall(r'struct (\w+_s) \{(.*?)\}\s*\w*\s*;', src, flags=re.S):
    fields = []
    for line in body.split(';'):
        line = ' '.join(line.split())
        if not line or line.startswith('struct game_aux_s'):
            continue
        m = re.match(r'BOOLVEC_DECLARE\((\w+), ([^)]*)\)$', line)
        if m:
            fields.append((m.group(1), 'uint8_t', [(num(m.group(2)) + 7) // 8]))
            continue
        m = re.match(r'BOOLVEC_TBL_DECLARE\((\w+), (\w+), ([^)]*)\)$', line)
        if m:
            fields.append((m.group(1), 'uint8_t', [num(m.group(2)), (num(m.group(3)) + 7) // 8]))
            continue
        m = re.match(r'(.*?)\s*(\w+)((?:\[[^\]]+\])*)$', line)
        ctype, fname, dims = m.group(1).replace('const ', ''), m.group(2), m.group(3)
        fields.append((fname, ctype, [num(x) for x in re.findall(r'\[([^\]]+)\]', dims)]))
    structs[name] = fields
typedefs = {'planet_t': 'planet_s', 'fleet_enroute_t': 'fleet_enroute_s', 'transport_t': 'transport_s',
            'fleet_orbit_t': 'fleet_orbit_s', 'techdata_t': 'techdata_s', 'shipresearch_t': 'shipresearch_s',
            'empiretechorbit_t': 'empiretechorbit_s', 'monster_t': 'monster_s', 'newtech_t': 'newtech_s',
            'nexttech_t': 'nexttech_s', 'newtechs_t': 'newtechs_s', 'gameevents_t': 'gameevents_s',
            'seen_t': 'seen_s', 'shipdesign_t': 'shipdesign_s'}
cl, al = [], []
var = [0]
def emit(sname, cpath, apath, prefix, ind, pargs):
    for fname, ctype, dims in structs[sname]:
        sub = typedefs.get(ctype)
        cp, ap = cpath + '.' + fname, apath + '.' + fname
        idx_c, idx_a, fmt, args_c, args_a = '', '', prefix + '.' + fname, pargs, pargs
        loops = []
        for n in dims:
            var[0] += 1
            v = 'i%d' % var[0]
            loops.append((v, n))
            idx_c += '[%s]' % v
            idx_a += '@(%s)' % v
            fmt += '[%i]'
            args_c += ', ' + v
            args_a += ', ' + v
        for k, (v, n) in enumerate(loops):
            cl.append('    ' * (ind + k) + 'for (int %s = 0; %s < %d; ++%s) {' % (v, v, n, v))
            al.append('    ' * (ind + k) + 'loop %s in %d {' % (v, n))
        k = ind + len(loops)
        if sub:
            emit(sub, cp + idx_c, ap + idx_a, fmt, k, args_c)
        else:
            if ctype == 'char':
                cv, av = '(int)(unsigned char)%s%s' % (cp, idx_c), '%s%s' % (ap, idx_a)
            elif ctype == 'bool':
                cv, av = '(int)%s%s' % (cp, idx_c), 'dbool(%s%s)' % (ap, idx_a)
            else:
                cv, av = '(long long)%s%s' % (cp, idx_c), '%s%s' % (ap, idx_a)
            cl.append('    ' * k + 'fprintf(f, "%s = %%lld\\n"%s, (long long)%s);' % (fmt, args_c, cv))
            al.append('    ' * k + 'set out@+ = string.format("%s = %%d\\n"%s, %s)' % (fmt, args_a, av))
        for j in range(len(loops) - 1, -1, -1):
            cl.append('    ' * (ind + j) + '}')
            al.append('    ' * (ind + j) + '}')
emit('game_s', '(*g)', 'g', 'g', 1, '')
open(sys.argv[2], 'w').write('/* The whole state of the game as text (generated by tools/gamedump.py).\n'
    '   The same lines as gamedump() of tst/gamedump.atm. Not part of the port. */\n'
    '#include <stdio.h>\n#include "game.h"\n\nstatic void gamedump(FILE *f, const struct game_s *g)\n{\n'
    + '\n'.join(cl) + '\n}\n')
open(sys.argv[3], 'w').write(';; The whole state of the game as text (generated by tools/gamedump.py).\n'
    ';; The same lines as gamedump() of tst/c/gamedump.h.\n\n'
    'func dbool (v) {\n    if v == true => 1 => (if v == false => 0 => v)\n}\n\n'
    'func gamedump (g) {\n    val out = []\n' + '\n'.join(al) + '\n    string.join(out, "")\n}\n')
print(len(cl), 'lines of C')
